(() => {
  'use strict';
  const { CONFIG } = window.Lake;
  const FISHING_STORIES = Object.freeze([
    ['Щука с характером', 'Однажды вытащил щуку — смотрит на меня так, будто я у неё без спроса удочку взял. Я спорить не стал, отпустил. С местными лучше дружить.'],
    ['Самая большая рыба', 'Самая большая рыба у меня всегда срывается у самого берега. Поэтому я теперь подальше сажусь. Пусть хоть до берега дорастёт, пока рассказываю.'],
    ['Правильная приманка', 'Как-то сосед весь день приманки менял, а я сидел с бутербродом. Рыбы у обоих — ни одной. Зато у меня обед был. Тоже результат.'],
    ['Термос важнее', 'Раз на рыбалку приехал и удочку дома оставил. Термос, правда, взял. Посидел у воды, чай попил. Думаю: а ведь день всё равно удался.'],
    ['Тихий напарник', 'Брал приятеля на рыбалку. Просил его сидеть потише — рыбу не пугать. Он уснул. Вот это я понимаю: человек ответственно к делу подошёл.'],
    ['Озёрный будильник', 'Будильник на четыре поставил, чтобы на утренний клёв успеть. Проснулся в восемь. Зато рыба к тому времени уже выспалась. Мы с ней одного мнения насчёт ранних подъёмов.'],
    ['Сапог и его история', 'Однажды сапог выловил. Без хозяина, зато с отличной поклёвкой. Домой не понёс — вдруг второй где-то рядом плавает и скучает.'],
    ['Секретное место', 'Один рыбак мне секретное место показал. Пришли — там ещё семеро сидят. Говорит: «Только никому не рассказывай». Видно, все семеро тоже надёжные люди.'],
    ['Прогноз по Сане', 'Раньше погоду по телефону смотрел. Теперь по себе: если за удочкой пошёл — дождь будет. Если дома остался — солнце. Можно меня вместо барометра на крыльце ставить.'],
    ['Комары тоже рыбаки', 'Комары у озера — рыбаки опытные. Приходят без снастей, а с уловом уходят всегда. Я им говорю: хоть лицензию покажите. Ни один пока не показал.'],
    ['Поплавок против телефона', 'Пробовал и на поплавок смотреть, и в телефон заглядывать. Рыба сразу поняла, кто тут главный. Теперь телефон в кармане лежит. Поплавок хотя бы уведомлений не присылает.'],
    ['Проверка терпения', 'Сидел как-то три часа без поклёвки. Потом поплавок дёрнулся — оказалось, я ногой леску задел. Но радость была настоящая. Её уже никто не отнимет.'],
    ['Уговор с рыбой', 'Я с рыбой уговорился: она не торопится клевать, я не тороплюсь домой. Пока обе стороны договор соблюдают. Редко встретишь такую ответственность.'],
    ['Рыбацкая линейка', 'У приятеля рыбацкая линейка была. Вчерашняя рыба по ней каждый день на сантиметр длиннее становилась. Хорошая вещь, только в ящик со снастями не помещалась — росла вместе с рыбой.'],
    ['Чай с видом', 'Дома чай как чай. А у озера тот же самый — будто особый сорт. Наверное, секретный ингредиент тут есть. Тишина называется. В магазине пока не встречал.'],
    ['Улов без ведра', 'Спрашивают иногда: «Что принёс с рыбалки?» Говорю: спокойную голову. В ведро не положишь, на весах не взвесишь. А домой с таким уловом идти приятно.']
  ].map(([title, text]) => Object.freeze({ title, text })));

  class FishingStoryManager {
    constructor({ onStory = () => {}, random = Math.random } = {}) {
      this.onStory = onStory;
      this.random = random;
      this.deck = [];
      this.lastStory = null;
      this.current = null;
      this.task = null;
    }
    next() {
      if (!this.deck.length) {
        this.deck = [...FISHING_STORIES];
        for (let i = this.deck.length - 1; i > 0; i--) {
          const j = Math.floor(this.random() * (i + 1));
          [this.deck[i], this.deck[j]] = [this.deck[j], this.deck[i]];
        }
        const last = this.deck.length - 1;
        if (this.deck[last] === this.lastStory) [this.deck[0], this.deck[last]] = [this.deck[last], this.deck[0]];
      }
      this.lastStory = this.deck.pop();
      return this.lastStory;
    }
    begin() {
      this.stop();
      this.current = this.next();
    }
    resume() {
      if (!this.current || this.task !== null) return;
      this.task = setTimeout(() => {
        this.task = null;
        this.current = this.next();
        this.onStory(this.current);
        this.resume();
      }, CONFIG.FISHING_STORY_INTERVAL);
    }
    pause() { clearTimeout(this.task); this.task = null; }
    stop() { this.pause(); this.current = null; }
  }
  window.Lake.FISHING_STORIES = FISHING_STORIES;
  window.Lake.FishingStoryManager = FishingStoryManager;
})();
